"""
STEP 5: For each site, combines the DataFrames generated by different TT Clouds when multiple TT Clouds are present.
"""

from pathlib import Path
import pandas as pd

# ---------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------
SITE_NAME = "valcanali"
CLOUD_ID_1 = "C1990068"
CLOUD_ID_2 = "C1990069"
FILES = [
    f"../data/output_data_tool/{SITE_NAME}/{CLOUD_ID_1}/df_all_{CLOUD_ID_1}.csv",
    # Uncomment the following line only if the second TT Cloud is available
    f"../data/output_data_tool/{SITE_NAME}/{CLOUD_ID_2}/df_all_{CLOUD_ID_2}.csv",
]

def extract_cloud_device_from_filename(filepath: str | Path) -> str:
    """
    Extract the serial of the TT Cloud device from the file name.

    E.g.:
    df_all_C1970065.csv -> C1970065
    """
    filepath = Path(filepath)
    stem = filepath.stem

    cloud_device = stem.replace("df_all_", "")

    return cloud_device


def read_harmonized_file(filepath: str | Path) -> pd.DataFrame:
    """
    Read an already harmonized CSV file and add the column cloud_device.
    """
    filepath = Path(filepath)

    df = pd.read_csv(filepath)

    cloud_device = extract_cloud_device_from_filename(filepath)

    df["cloud_device"] = cloud_device

    return df


def merge_harmonized_files(filepaths: list[str | Path]) -> pd.DataFrame:
    """
    Read multiple CSV harmonized files, add cloud_device column and merge them in a unique DataFrame.
    """
    dfs = []
    total_rows = 0

    for filepath in filepaths:
        df = read_harmonized_file(filepath)
        print(f"{filepath}: {len(df)} righe")
        total_rows += len(df)
        dfs.append(df)

    df_final = pd.concat(dfs, ignore_index=True)

    print(f"Total input rows: {total_rows}")
    print(f"DF final rows: {len(df_final)}")

    return df_final


def main() -> None:
    df_merged = merge_harmonized_files(FILES)

    df_merged.to_csv(f"../data/output_data_tool/{SITE_NAME}/df_merged_{SITE_NAME}.csv", index=False)

if __name__ == "__main__":
    main()